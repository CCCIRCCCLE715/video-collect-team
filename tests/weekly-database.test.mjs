import test from 'node:test';
import assert from 'node:assert/strict';
import {readFile,readdir} from 'node:fs/promises';
import {pathToFileURL} from 'node:url';
import {normalizeTopic} from '../assets/topic.js';
const {PGlite}=await import(process.env.PGLITE_MODULE?pathToFileURL(process.env.PGLITE_MODULE).href:'@electric-sql/pglite');
const {pgcrypto}=await import(process.env.PGLITE_CRYPTO_MODULE?pathToFileURL(process.env.PGLITE_CRYPTO_MODULE).href:'@electric-sql/pglite/contrib/pgcrypto');
test('weekly collections preserve archives, isolate owners, deduplicate within a week and catch up empty tables',async()=>{
 const db=new PGlite({extensions:{pgcrypto}});
 try{
  await db.exec(`create role anon; create role authenticated; create role service_role bypassrls;
   create schema auth; create table auth.users(id uuid primary key,email text);
   create function auth.uid() returns uuid language sql stable as $$select nullif(current_setting('request.jwt.claim.sub',true),'')::uuid$$;
   grant usage on schema auth,public to anon,authenticated,service_role;
   grant execute on function auth.uid() to anon,authenticated,service_role;
   create schema storage;
   create table storage.buckets(id text primary key,name text,public boolean,file_size_limit bigint,allowed_mime_types text[]);
   create table storage.objects(id bigserial primary key,bucket_id text,name text);
   alter table storage.objects enable row level security;
   create function storage.foldername(text) returns text[] language sql immutable as $$select string_to_array($1,'/')$$;`);
  await db.exec(await readFile(new URL('../supabase/migrations/202610130001_team.sql',import.meta.url),'utf8'));
  const ids=Array.from({length:5},(_,n)=>`${n+1}1111111-1111-1111-1111-111111111111`);
  for(const id of ids)await db.query('insert into auth.users(id) values($1)',[id]);
  for(let n=0;n<4;n++)await db.query('insert into team_members values($1,$2)',[ids[n],['黄白','正源','豹朴','弈伶'][n]]);
  const as=async(role,id,sql,args=[])=>{await db.exec(`set role ${role}`);await db.query("select set_config('request.jwt.claim.sub',$1,false)",[id||'']);try{return await db.query(sql,args);}finally{await db.exec('reset role');}};
  const old=normalizeTopic({url:'https://www.instagram.com/reel/Old123/',summary:'原有记录。'});
  await as('authenticated',ids[0],'select upsert_topic($1::jsonb)',[JSON.stringify(old)]);
  await db.exec("update topics set created_at='2026-10-14T12:00:00Z'");
  const files=await readdir(new URL('../supabase/migrations/',import.meta.url));
  await db.exec(await readFile(new URL('../supabase/migrations/'+files.find(x=>x.endsWith('_member_weekly_tables.sql')),import.meta.url),'utf8'));
  await db.exec(await readFile(new URL('../supabase/migrations/20261014152055_member_identity.sql',import.meta.url),'utf8'));
  await db.query('update auth.users set email=$1 where id=$2',['two@example.test',ids[1]]);
  const identity=(await as('authenticated',ids[1],'select current_team_member() as member')).rows[0].member;
  assert.deepEqual(identity,{user_id:ids[1],name:'正源',email:'two@example.test'});
  await assert.rejects(as('anon',null,'select current_team_member()'),/permission denied/);
  await assert.rejects(as('authenticated',ids[4],'select current_team_member()'),/未加入团队/);
  await assert.rejects(db.query("update team_members set name='正源' where user_id=$1",[ids[0]]),/unique/);
  await db.exec(await readFile(new URL('../supabase/migrations/'+files.find(x=>x.endsWith('_personal_favorites.sql')),import.meta.url),'utf8'));
  assert.equal((await as('authenticated',ids[2],'select current_team_member() as member')).rows[0].member.name,'豹朴');
  assert.equal((await as('authenticated',ids[3],'select current_team_member() as member')).rows[0].member.name,'奕伶');
  assert.equal((await db.query('select count(*)::int as n from member_topic_entries')).rows[0].n,1,'migration must preserve existing entries');
  assert.equal((await db.query("select name from team_members where user_id=$1",[ids[2]])).rows[0].name,'豹朴');
  await assert.rejects(as('anon',null,'select list_weekly_topics()'),/permission denied/);
  await assert.rejects(as('authenticated',ids[4],'select list_weekly_topics()'),/未加入团队/);
  await assert.rejects(as('authenticated',ids[0],"select app_private.ensure_library_weeks('2026-10-21T00:00:00Z')"),/permission denied/);
  for(const [at,want] of [['2026-10-13T15:59:59Z','2026-10-07'],['2026-10-13T16:00:00Z','2026-10-14'],['2026-10-20T15:59:59Z','2026-10-14'],['2026-10-20T16:00:00Z','2026-10-21']]){
   assert.equal((await db.query('select app_private.collection_week($1)::text as week',[at])).rows[0].week,want);
  }
  const topic={...normalizeTopic({url:'https://www.instagram.com/reel/Weekly123/',summary:'第一周的总结。'}),owner_id:ids[3],week_start:'2099-01-01'};
  const capture=async(member,at,input=topic)=>(await db.query('select app_private.capture_topic($1,$2::jsonb,null,$3) as id',[member,JSON.stringify(input),at])).rows[0].id;
  const first=await capture(ids[0],'2026-10-14T02:00:00Z');
  assert.equal(await capture(ids[0],'2026-10-20T15:59:59Z'),first);
  const other=await capture(ids[1],'2026-10-14T02:00:00Z',{...topic,summary:'正源的总结。'});
  assert.notEqual(other,first);
  const next=await capture(ids[0],'2026-10-20T16:00:00Z',{...topic,summary:'第二周的总结。'});
  assert.notEqual(next,first);
  const entries=(await as('authenticated',ids[1],'select list_weekly_topics() as rows')).rows[0].rows;
  assert.equal(entries.find(x=>x.id===first).summary,'第一周的总结。');
  assert.equal(entries.find(x=>x.id===other).summary,'正源的总结。');
  assert.equal(entries.find(x=>x.id===next).week_start,'2026-10-21');
  assert.equal(entries.find(x=>x.id===first).owner_id,ids[0]);
  assert.equal(entries.find(x=>x.id===first).week_start,'2026-10-14');
  const browserTopic=normalizeTopic({url:'https://www.instagram.com/reel/Browser123/'});
  await as('authenticated',ids[0],'select upsert_topic($1::jsonb)',[JSON.stringify(browserTopic)]);
  assert.equal((await db.query('select count(*)::int as n from member_topic_entries where topic_id=$1',[browserTopic.id])).rows[0].n,1,'Browser and Agent imports must both create a weekly entry');
  await as('authenticated',ids[1],'select set_topic_favorite($1,true)',[first]);
  await as('authenticated',ids[1],'select set_topic_favorite($1,true)',[next]);
  assert.equal((await as('authenticated',ids[1],'select count(*)::int as n from topic_favorites')).rows[0].n,1,'Repeated video likes must merge across member and week copies');
  assert.equal((await as('authenticated',ids[0],'select count(*)::int as n from topic_favorites where user_id=$1',[ids[1]])).rows[0].n,1,'Team members may view each other’s separate collections');
  assert.equal((await as('authenticated',ids[4],'select count(*)::int as n from topic_favorites')).rows[0].n,0,'Non-members cannot read team collections');

  await assert.rejects(as('anon',null,'select * from topic_favorites'),/permission denied/);
  await assert.rejects(as('authenticated',ids[4],'select set_topic_favorite($1,true)',[first]),/未加入团队/);
  await as('authenticated',ids[0],'select set_topic_favorite($1,true,$2)',[first,ids[0]]);
  await as('authenticated',ids[1],'select set_topic_favorite($1,false,$2)',[first,ids[0]]);
  assert.equal((await as('authenticated',ids[1],'select count(*)::int as n from topic_favorites where user_id=$1',[ids[0]])).rows[0].n,0,'Any teammate can remove a favorite from the selected member collection');
  await as('authenticated',ids[1],'select set_topic_favorite($1,true,$2)',[first,ids[0]]);
  assert.equal((await as('authenticated',ids[0],'select count(*)::int as n from topic_favorites where user_id=$1',[ids[0]])).rows[0].n,1,'Any teammate can add to another member collection');
  await as('authenticated',ids[1],'select set_topic_favorite($1,false,$2)',[first,ids[0]]);
  await assert.rejects(as('authenticated',ids[0],'insert into topic_favorites(user_id,topic_id,entry_id) values($1,$2,$3)',[ids[0],old.id,first]),/row-level security/);
  await as('authenticated',ids[0],'select set_topic_favorite($1,false)',[first]);
  assert.equal((await as('authenticated',ids[1],'select count(*)::int as n from topic_favorites')).rows[0].n,1,'Unliking must affect only the signed-in member');
  await as('authenticated',ids[1],'select set_topic_favorite($1,false)',[other]);
  assert.equal((await as('authenticated',ids[1],'select count(*)::int as n from topic_favorites')).rows[0].n,0);
  await assert.rejects(as('authenticated',ids[1],'select set_topic_favorite($1,true)',['00000000-0000-0000-0000-000000000000']),/不存在/);
  await assert.rejects(as('authenticated',ids[1],'select set_entry_deleted($1,true)',[first]),/自己的选题/);
  await as('authenticated',ids[0],'select set_entry_deleted($1,true)',[first]);
  let rows=(await as('authenticated',ids[0],'select list_weekly_topics() as rows')).rows[0].rows;
  assert.ok(rows.find(x=>x.id===first).deleted_at);
  assert.equal(rows.find(x=>x.id===other).deleted_at,null);
  assert.equal(rows.find(x=>x.id===next).deleted_at,null);
  await as('authenticated',ids[0],'select set_entry_deleted($1,false)',[first]);
  assert.equal((await db.query('select deleted_at from member_topic_entries where id=$1',[first])).rows[0].deleted_at,null);
  await db.query("select app_private.ensure_library_weeks('2026-11-04T00:00:00Z')");
  await db.query("select app_private.ensure_library_weeks('2026-11-04T00:00:00Z')");
  assert.equal((await db.query("select count(*)::int as n from member_week_tables where week_start='2026-11-04'")).rows[0].n,4);
  assert.equal((await db.query("select count(*)::int as n from member_topic_entries where week_start='2026-11-04'")).rows[0].n,0);
  assert.equal((await db.query("select count(*)::int as n from library_weeks where start_date between '2026-10-14' and '2026-11-04'")).rows[0].n,4);
  await assert.rejects(as('authenticated',ids[0],'delete from member_topic_entries'),/permission denied/);
  const path=ids[0]+'/'+'f'.repeat(32)+'.png';
  await db.query("insert into storage.objects(bucket_id,name) values('covers',$1)",[path]);
  await assert.rejects(as('authenticated',ids[1],'select replace_entry_cover($1,$2)',[first,path]),/自己的选题/);
  await as('authenticated',ids[0],'select replace_entry_cover($1,$2)',[first,path]);
  assert.equal((await db.query('select cover_path from member_topic_entries where id=$1',[first])).rows[0].cover_path,path);
  assert.equal((await db.query('select cover_path from member_topic_entries where id=$1',[next])).rows[0].cover_path,null);
 }finally{await db.close();}
});
